package com.homerelay.app.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.layout.size
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.runtime.collectAsState
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import com.homerelay.app.state.AppState
import com.homerelay.app.state.SharingPhase
import com.homerelay.app.ui.QrImage
import com.homerelay.app.ui.SectionCard

@Composable
fun GuideScreen() {
    val state = AppState.state.collectAsState().value
    val sharing = state.phase == SharingPhase.Sharing
    val host = state.bindAddress ?: "<hotspot-ip>"
    val port = state.proxyPort
    val pacUrl = state.pacUrl ?: "http://$host:$port/proxy.pac"

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = androidx.compose.foundation.layout.PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        item {
            SectionCard(title = "1. Turn sharing on") {
                Text(
                    "On the HomeRelay phone, tap “Start sharing”. HomeRelay asks Android for a " +
                        "local-only hotspot, then binds its HTTP proxy to that hotspot only. Your " +
                        "home Wi-Fi keeps working exactly as before — HomeRelay never changes it.",
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
        }
        item {
            SectionCard(title = "2. Connect the client to the hotspot") {
                if (sharing) {
                    InfoLine("SSID", state.hotspotSsid ?: "Unavailable (Android hid it)")
                    InfoLine("Password", state.hotspotPassphrase ?: "Unavailable")
                } else {
                    Text(
                        "Join the hotspot named on the Dashboard once sharing is on. The name and password are generated by Android on each activation — check them on the Dashboard (or the persistent notification) before connecting.",
                        style = MaterialTheme.typography.bodyMedium,
                    )
                }
                Text(
                    "The hotspot has no internet of its own. Internet reaches clients only through the proxy below.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
        item {
            SectionCard(title = "3. Point the client at the proxy") {
                InfoLine("Host", host)
                InfoLine("Port", "$port")
                InfoLine("Scheme", "HTTP (covers HTTPS via CONNECT tunnels)")
                if (sharing && state.pacUrl != null) {
                    InfoLine("PAC URL", state.pacUrl!!)
                }
                Text(
                    "Android (most versions): Settings → Connections → Wi-Fi → the HomeRelay network → Manage/Details → Advanced → Proxy → Manual → hostname and port above. " +
                        "Or choose “Proxy auto-config” and paste the PAC URL.",
                    style = MaterialTheme.typography.bodyMedium,
                    modifier = Modifier.padding(top = 4.dp),
                )
                Text(
                    "iPhone / iPad: Settings → Wi-Fi → ⓘ on the hotspot → Configure Proxy → Manual → Server + Port (or Automatic with the PAC URL).\n" +
                        "Windows: Settings → Network & Internet → Wi-Fi → hardware properties → Proxy → Manual setup → Use a proxy server → Address + Port.\n" +
                        "macOS: System Settings → Wi-Fi → Details… → Proxies → Web proxy + Secure web proxy (same host/port) or “Automatic Proxy Configuration” with the PAC URL.\n" +
                        "ChromeOS: Settings → Network → the hotspot → Network → Proxy → Manual / PAC URL.\n" +
                        "Linux (desktop): Settings → Network → proxy → manual, or export http_proxy/https_proxy=http://host:port for a shell.\n" +
                        "Firefox uses its own proxy settings (Settings → Network Settings) independent of the OS.",
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
        }
        item {
            SectionCard(title = "QR helper") {
                Text(
                    "This QR encodes the PAC URL. A stock phone camera opens it in a browser, confirming the address. " +
                        "It does NOT auto-configure the proxy — no current Android/iOS version lets an app configure a Wi-Fi proxy from a QR. Manual setup above is always required.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Row(
                    Modifier.fillMaxWidth().padding(top = 8.dp),
                    horizontalArrangement = Arrangement.Center,
                ) {
                    QrImage(text = pacUrl, size = 200.dp)
                }
            }
        }
        item {
            SectionCard(title = "4. Verify") {
                Text(
                    "On the client, open a plain HTTP page (e.g. connectivitycheck.gstatic.com/generate_204) " +
                        "and an HTTPS page (e.g. https://www.wikipedia.org). If HTTPS fails but HTTP works, the client is not actually using the proxy — recheck step 3.",
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
        }
        item {
            SectionCard(title = "Good to know (honest limits)") {
                Text(
                    "• Proxy sharing ≠ transparent bridge. Apps that ignore the Wi-Fi proxy get no internet through this hotspot.\n" +
                        "• HTTPS is never decrypted — CONNECT tunnels carry opaque bytes; certificates stay end-to-end.\n" +
                        "• Same-SSID/same-password setups are just matching credentials — not mesh, roaming, or repeater behavior.\n" +
                        "• All traffic exits the phone via its Wi-Fi. Nothing touches mobile data.\n" +
                        "• LocalOnlyHotspot name/password are random per activation on Android 12+; HomeRelay cannot set them.\n" +
                        "• If One UI kills the service, raise the notification, re-open HomeRelay, or exempt it from battery optimization (Settings → One UI battery & background limits).",
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
        }
    }
}

@Composable
private fun InfoLine(label: String, value: String) {
    Column(Modifier.padding(vertical = 2.dp)) {
        Text(
            label,
            style = MaterialTheme.typography.labelMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Text(
            value,
            style = MaterialTheme.typography.titleMedium.copy(fontFamily = FontFamily.Monospace, fontWeight = FontWeight.SemiBold),
        )
    }
}
